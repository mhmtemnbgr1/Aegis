import subprocess
from pathlib import Path

import pytest

from aegis.diff import (
    FileDiff,
    FileStatus,
    LineKind,
    SkipReason,
    filter_diff,
    git_diff,
    load_ignore_spec,
    parse_diff,
)

MODIFIED = """\
diff --git a/app/db.py b/app/db.py
index 1111111..2222222 100644
--- a/app/db.py
+++ b/app/db.py
@@ -10,3 +10,4 @@ class Pool:
     def release(self, conn):
-        self.free.append(conn)
+        if conn is not None:
+            self.free.append(conn)
         return None
"""

ADDED = """\
diff --git a/app/new.py b/app/new.py
new file mode 100644
index 0000000..3333333
--- /dev/null
+++ b/app/new.py
@@ -0,0 +1,2 @@
+import os
+print(os.getcwd())
"""

DELETED = """\
diff --git a/app/old.py b/app/old.py
deleted file mode 100644
index 4444444..0000000
--- a/app/old.py
+++ /dev/null
@@ -1 +0,0 @@
-x = 1
"""

RENAMED_PURE = """\
diff --git a/src/a.py b/src/b.py
similarity index 100%
rename from src/a.py
rename to src/b.py
"""

BINARY = """\
diff --git a/img/logo.png b/img/logo.png
index 5555555..6666666 100644
Binary files a/img/logo.png and b/img/logo.png differ
"""


def _diff_file(path: str, first_line: str = "x = 1") -> str:
    return (
        f"diff --git a/{path} b/{path}\n"
        "index 1111111..2222222 100644\n"
        f"--- a/{path}\n"
        f"+++ b/{path}\n"
        "@@ -1 +1 @@\n"
        "-old\n"
        f"+{first_line}\n"
    )


def test_parse_modified_lines_and_numbers() -> None:
    diff = parse_diff(MODIFIED)
    [f] = diff.files
    assert f.path == "app/db.py"
    assert f.status is FileStatus.MODIFIED
    assert (f.added, f.removed) == (2, 1)
    [hunk] = f.hunks
    assert (hunk.old_start, hunk.old_length, hunk.new_start, hunk.new_length) == (10, 3, 10, 4)
    assert hunk.section == "class Pool:"
    assert [line.kind for line in hunk.lines] == [
        LineKind.CONTEXT,
        LineKind.REMOVED,
        LineKind.ADDED,
        LineKind.ADDED,
        LineKind.CONTEXT,
    ]
    assert hunk.lines[1].content == "        self.free.append(conn)"
    assert f.changed_new_lines == {11, 12}


def test_parse_added_and_deleted() -> None:
    diff = parse_diff(ADDED + DELETED)
    added, deleted = diff.files
    assert added.status is FileStatus.ADDED
    assert added.old_path is None
    assert added.changed_new_lines == {1, 2}
    assert deleted.path == "app/old.py"
    assert deleted.status is FileStatus.DELETED
    assert (deleted.added, deleted.removed) == (0, 1)
    assert deleted.changed_new_lines == set()


def test_parse_pure_rename_without_hunks() -> None:
    [f] = parse_diff(RENAMED_PURE).files
    assert f.status is FileStatus.RENAMED
    assert (f.path, f.old_path) == ("src/b.py", "src/a.py")
    assert f.hunks == []


def test_parse_binary() -> None:
    [f] = parse_diff(BINARY).files
    assert f.is_binary
    assert f.hunks == []


def test_parse_empty() -> None:
    diff = parse_diff("")
    assert diff.files == []
    assert diff.added == diff.removed == 0


def test_diff_totals_and_lookup() -> None:
    diff = parse_diff(MODIFIED + ADDED)
    assert (diff.added, diff.removed) == (4, 1)
    assert diff.get("app/new.py") is not None
    assert diff.get("missing.py") is None


@pytest.mark.parametrize(
    ("path", "first_line", "reason"),
    [
        ("uv.lock", "x", SkipReason.LOCK),
        ("web/package-lock.json", "x", SkipReason.LOCK),
        ("static/app.min.js", "x", SkipReason.MINIFIED),
        ("static/app.js.map", "x", SkipReason.MINIFIED),
        ("proto/user_pb2.py", "x", SkipReason.GENERATED),
        ("ui/__generated__/types.ts", "x", SkipReason.GENERATED),
        ("app/migrations/0002.py", "# Generated by Django 5.0 on 2026-01-01", SkipReason.GENERATED),
        ("app/models.py", "# @generated by tool", SkipReason.GENERATED),
        ("app/models.py", "x = 1", None),
        ("app/lock.py", "x = 1", None),
    ],
)
def test_skip_reasons(path: str, first_line: str, reason: SkipReason | None) -> None:
    result = filter_diff(parse_diff(_diff_file(path, first_line)))
    if reason is None:
        assert result.skipped == []
        assert [f.path for f in result.diff.files] == [path]
    else:
        assert [(s.path, s.reason) for s in result.skipped] == [(path, reason)]
        assert result.diff.files == []


def test_filter_keeps_deleted_and_renamed_drops_binary() -> None:
    result = filter_diff(parse_diff(DELETED + RENAMED_PURE + BINARY))
    assert [f.path for f in result.diff.files] == ["app/old.py", "src/b.py"]
    assert [(s.path, s.reason) for s in result.skipped] == [("img/logo.png", SkipReason.BINARY)]


def test_filter_aegisignore_patterns() -> None:
    diff = parse_diff(_diff_file("docs/conf.py") + _diff_file("vendor/lib.py") + MODIFIED)
    result = filter_diff(diff, ignore=["docs/", "vendor/**", "!vendor/keep.py"])
    assert [f.path for f in result.diff.files] == ["app/db.py"]
    assert {s.reason for s in result.skipped} == {SkipReason.IGNORED}


def test_load_ignore_spec(tmp_path: Path) -> None:
    (tmp_path / ".aegisignore").write_text("# yorum\nlegacy/\n", encoding="utf-8")
    spec = load_ignore_spec(tmp_path)
    assert spec.match_file("legacy/old.py")
    assert not spec.match_file("app/new.py")
    assert not load_ignore_spec(tmp_path / "missing").match_file("legacy/old.py")


def test_filter_too_large() -> None:
    result = filter_diff(parse_diff(MODIFIED), max_changed_lines=2)
    assert [s.reason for s in result.skipped] == [SkipReason.TOO_LARGE]
    assert filter_diff(parse_diff(MODIFIED), max_changed_lines=3).skipped == []


def _git(repo: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=repo, check=True, capture_output=True)


def test_git_diff_end_to_end(tmp_path: Path) -> None:
    _git(tmp_path, "init", "-q", "-b", "main")
    _git(tmp_path, "config", "user.email", "t@example.com")
    _git(tmp_path, "config", "user.name", "t")
    _git(tmp_path, "config", "core.autocrlf", "false")
    body = "".join(f"line{i}\n" for i in range(10))
    (tmp_path / "old.py").write_text(body, encoding="utf-8")
    (tmp_path / "gone.py").write_text("x = 1\n", encoding="utf-8")
    (tmp_path / "data.bin").write_bytes(b"\x00\x01\x02")
    _git(tmp_path, "add", ".")
    _git(tmp_path, "commit", "-q", "-m", "base")
    _git(tmp_path, "checkout", "-q", "-b", "feature")
    _git(tmp_path, "mv", "old.py", "renamed.py")
    (tmp_path / "renamed.py").write_text(body + "line10\n", encoding="utf-8")
    _git(tmp_path, "rm", "-q", "gone.py")
    (tmp_path / "data.bin").write_bytes(b"\x00\x09\x02")
    (tmp_path / "çıktı.py").write_text("print('merhaba')\n", encoding="utf-8")
    _git(tmp_path, "add", "-A")
    _git(tmp_path, "commit", "-q", "-m", "change")

    diff = parse_diff(git_diff("main", "feature", repo=tmp_path))
    by_path: dict[str, FileDiff] = {f.path: f for f in diff.files}
    assert by_path["renamed.py"].status is FileStatus.RENAMED
    assert by_path["renamed.py"].old_path == "old.py"
    assert by_path["renamed.py"].changed_new_lines == {11}
    assert by_path["gone.py"].status is FileStatus.DELETED
    assert by_path["data.bin"].is_binary
    assert by_path["çıktı.py"].status is FileStatus.ADDED
