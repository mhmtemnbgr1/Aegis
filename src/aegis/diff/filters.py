"""İncelemeye değmeyen dosyaları (binary, lock, minified, üretilmiş) diff'ten ayıklar."""

from collections.abc import Iterable
from enum import StrEnum
from pathlib import Path

from pathspec import GitIgnoreSpec
from pydantic import BaseModel, Field

from aegis.diff.models import Diff, FileDiff

AEGISIGNORE = ".aegisignore"

LOCK_FILES = frozenset(
    {
        "uv.lock",
        "poetry.lock",
        "Pipfile.lock",
        "pdm.lock",
        "package-lock.json",
        "npm-shrinkwrap.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "bun.lockb",
        "Cargo.lock",
        "Gemfile.lock",
        "composer.lock",
        "go.sum",
    }
)

MINIFIED_PATTERNS = ("*.min.js", "*.min.css", "*.map")

GENERATED_PATTERNS = (
    "*_pb2.py",
    "*_pb2.pyi",
    "*_pb2_grpc.py",
    "**/__generated__/**",
)

# Üretilmiş dosyaların başlığında sık görülen işaretler.
GENERATED_MARKERS = ("@generated", "DO NOT EDIT", "Generated by Django")

_MARKER_SCAN_LINES = 5


class SkipReason(StrEnum):
    BINARY = "binary"
    LOCK = "lock"
    MINIFIED = "minified"
    GENERATED = "generated"
    IGNORED = "aegisignore"
    TOO_LARGE = "too-large"


class SkippedFile(BaseModel):
    path: str
    reason: SkipReason


class FilterResult(BaseModel):
    diff: Diff
    skipped: list[SkippedFile] = Field(default_factory=list)


_MINIFIED_SPEC = GitIgnoreSpec.from_lines(MINIFIED_PATTERNS)
_GENERATED_SPEC = GitIgnoreSpec.from_lines(GENERATED_PATTERNS)


def load_ignore_spec(repo: Path | str = ".") -> GitIgnoreSpec:
    """Repo kökündeki `.aegisignore` dosyasını (gitignore sözdizimi) okur."""
    path = Path(repo) / AEGISIGNORE
    lines = path.read_text(encoding="utf-8").splitlines() if path.is_file() else []
    return GitIgnoreSpec.from_lines(lines)


def _has_generated_marker(f: FileDiff) -> bool:
    head = [line.content for h in f.hunks for line in h.lines][:_MARKER_SCAN_LINES]
    return any(marker in line for line in head for marker in GENERATED_MARKERS)


def skip_reason(
    f: FileDiff,
    ignore: GitIgnoreSpec | None = None,
    max_changed_lines: int | None = None,
) -> SkipReason | None:
    """Dosya elenecekse nedenini, incelenecekse `None` döndürür."""
    name = f.path.rsplit("/", 1)[-1]
    if f.is_binary:
        return SkipReason.BINARY
    if name in LOCK_FILES:
        return SkipReason.LOCK
    if _MINIFIED_SPEC.match_file(f.path):
        return SkipReason.MINIFIED
    if _GENERATED_SPEC.match_file(f.path) or _has_generated_marker(f):
        return SkipReason.GENERATED
    if ignore is not None and ignore.match_file(f.path):
        return SkipReason.IGNORED
    if max_changed_lines is not None and f.added + f.removed > max_changed_lines:
        return SkipReason.TOO_LARGE
    return None


def filter_diff(
    diff: Diff,
    ignore: GitIgnoreSpec | Iterable[str] | None = None,
    max_changed_lines: int | None = None,
) -> FilterResult:
    """İncelenecek dosyaları ve elenenleri nedenleriyle birlikte döndürür.

    `ignore` hazır bir `GitIgnoreSpec` ya da gitignore sözdiziminde desen listesi olabilir.
    """
    spec = (
        ignore
        if ignore is None or isinstance(ignore, GitIgnoreSpec)
        else GitIgnoreSpec.from_lines(ignore)
    )
    kept: list[FileDiff] = []
    skipped: list[SkippedFile] = []
    for f in diff.files:
        reason = skip_reason(f, spec, max_changed_lines)
        if reason is None:
            kept.append(f)
        else:
            skipped.append(SkippedFile(path=f.path, reason=reason))
    return FilterResult(diff=Diff(files=kept), skipped=skipped)
